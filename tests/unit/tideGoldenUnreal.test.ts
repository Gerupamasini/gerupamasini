import { describe, it, expect } from 'vitest';
import { TideModel, type TideStationData } from '../../src/tide/TideModel';
import tokyo from '../../public/data/tide/stations/jma_tokyo.json';
import yokosuka from '../../public/data/tide/stations/jma_yokosuka.json';
import manko from '../../public/data/tide/stations/manko_demo.json';

// Golden fixtures for the UE5 port of the tide model (unreal/HigataZukan/Source/HigataTide/…/TideCore.cpp).
// The C++ test (unreal/tests/tide) reads the same files. After a deliberate change to src/tide, regenerate with
// `npx vitest run tests/unit/tideGoldenUnreal.test.ts -u` and port the change to TideCore.cpp.

const DAY = 86400000;
const tokyoData = tokyo as TideStationData;
const stations: TideStationData[] = [
  tokyoData,
  yokosuka as TideStationData,
  manko as TideStationData,
  // The bundled stations are all UTC-referenced; these exercise the two JST conventions.
  { ...tokyoData, id: 'tokyo_jst_zone', phaseReference: 'JST135E', phaseConvention: 'zone_speed' },
  { ...tokyoData, id: 'tokyo_jst_meridian', phaseReference: 'JST135E', phaseConvention: 'meridian_species' },
];

/** Sample epochs from 1970 to 2060, plus a dense day, all whole milliseconds. */
function sampleTimes(): number[] {
  const out: number[] = [];
  const start = Date.UTC(1970, 0, 1, 3, 17, 41);
  for (let k = 0; k < 120; k++) out.push(start + k * (275 * DAY + 7 * 3600000 + 13 * 60000 + 7));
  const day = Date.UTC(2026, 9, 11);
  for (let m = 0; m < 24 * 60; m += 20) out.push(day + m * 60000);
  out.push(Date.UTC(1969, 11, 31, 23, 0, 0)); // a negative epoch
  return out;
}

const extremaWindows = [Date.UTC(2000, 0, 1), Date.UTC(2026, 6, 20), Date.UTC(2026, 9, 11), Date.UTC(2055, 2, 3)];

function fixture(st: TideStationData): string {
  const model = new TideModel(st);
  const lines = [
    '# Generated by tests/unit/tideGoldenUnreal.test.ts from src/tide. Do not edit by hand.',
    `station ${st.id} ${st.phaseReference} ${st.phaseConvention ?? 'zone_speed'}`,
    ...st.constituents.map((c) => `c ${c.name} ${String(c.amplitude_cm)} ${String(c.phase_deg)}`),
    `max ${String(model.maxAmplitude())}`,
  ];
  for (const t of sampleTimes()) lines.push(`level ${t} ${String(model.level(t))}`);
  for (const t of sampleTimes().slice(0, 40)) lines.push(`rate ${t} ${String(model.rate(t))}`);
  for (const from of extremaWindows) {
    lines.push(`window ${from} ${from + 3 * DAY}`);
    for (const e of model.extrema(from, from + 3 * DAY)) lines.push(`extremum ${String(e.t)} ${String(e.level)} ${e.kind}`);
  }
  return lines.join('\n') + '\n';
}

describe('tide golden fixtures for the UE5 port', () => {
  for (const st of stations) {
    it(st.id, async () => {
      await expect(fixture(st)).toMatchFileSnapshot(`../../unreal/tests/tide/fixtures/${st.id}.txt`);
    });
  }
});
