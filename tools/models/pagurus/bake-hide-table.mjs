#!/usr/bin/env node
// Bakes the withdrawal poses of ユビナガホンヤドカリ (hidden body pose, P2/P3 folds, claw lids) per shell
// species × size bin (shell size / shield length, 5 % steps) × sex into
// src/creatures/yubinagahonyadokari/PagurusMinutusHideTable.js. The searches take 0.2–1 s each, too long
// to run in a game frame. Run after changing the morphology, the shells or PagurusMinutusHide.js:
//   npm run model:pagurus-hide
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as THREE from 'three';
import { HermitCrab } from '../../../src/creatures/yubinagahonyadokari/PagurusMinutus.js';
import { SHELL_SPECIES, SHELL_SPECIES_KEYS } from '../../../src/creatures/yubinagahonyadokari/PagurusMinutusShell.js';
import { encode, hideSignature, setHideTableEnabled, binRatio } from '../../../src/creatures/yubinagahonyadokari/PagurusMinutusHide.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const out = path.join(root, 'src', 'creatures', 'yubinagahonyadokari', 'PagurusMinutusHideTable.js');
const STEP = Math.log(1.05);
const SL = 4.8; // any: everything scales with the shield length

setHideTableEnabled(false);
const table = { sig: hideSignature(), bins: {}, pose: {}, legs: {}, claws: {} };
const t0 = Date.now();
for (const key of SHELL_SPECIES_KEYS) {
  const fit = SHELL_SPECIES[key].hideFit;
  // from tight shells (the crab cannot fully withdraw) to roomy ones
  const lo = Math.round(Math.log(fit * 0.6) / STEP), hi = Math.round(Math.log(fit * 2.0) / STEP);
  table.bins[key] = [lo, hi];
  for (let bin = lo; bin <= hi; bin++) {
    for (const sex of ['m', 'f']) {
      const crab = new HermitCrab({ seed: 7, sex, shieldLength_mm: SL, lod: 2, shell: { species: key, size_mm: SL * binRatio(bin), seed: 1 } });
      crab.placeAt(new THREE.Vector3(), 0, { groundAt: () => 0 });
      const k = `${key}|${bin}`;
      if (sex === 'm') {
        table.pose[k] = encode.pose(crab);
        table.legs[k] = encode.legs(crab);
      }
      table.claws[`${k}|${sex}`] = encode.claws(crab);
      crab.dispose();
    }
    process.stdout.write(`\r${key} ${bin - lo + 1}/${hi - lo + 1}   `);
  }
  process.stdout.write('\n');
}
const body = JSON.stringify(table).replace(/\],"/g, '],\n"');
fs.writeFileSync(out, `// Generated by tools/models/pagurus/bake-hide-table.mjs – do not edit. Regenerate after changing the
// morphology, the shells or the withdrawal searches (npm run model:pagurus-hide).
export const HIDE_TABLE = ${body};
`);
console.log(`wrote ${path.relative(root, out)} (${Object.keys(table.pose).length} poses, ${((Date.now() - t0) / 1000).toFixed(0)} s, sig ${table.sig})`);
